/** A finding as produced by a check, before it is stored. */
export const FindingInput = z.object({
  category: z.enum(CHECK_CATEGORIES),
  rule: z.string().min(1), // stable id, e.g. "seo.title-missing", "axe.button-name"
  severity: z.enum(SEVERITIES),
  title: z.string().min(1),
  url: z.string().url(),
  detail: z.string().optional(),
  wcag: z.string().optional(), // e.g. "4.1.2"
  selector: z.string().optional(),
  evidence: z.record(z.unknown()).optional(),
});
export type FindingInput = z.infer<typeof FindingInput>;

/**
 * Fingerprint used to dedupe a finding across runs.
 * Same rule + same URL path + same selector = same finding, even if wording changes.
 */
export function findingFingerprint(f: Pick<FindingInput, "rule" | "url" | "selector">): string {
  const u = new URL(f.url);
  const key = [f.rule, u.host, u.pathname.replace(/\/+$/, "") || "/", f.selector ?? ""].join("|");
  return createHash("sha256").update(key).digest("hex").slice(0, 32);
}

